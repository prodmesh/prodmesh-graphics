test('item data is validated against the pinned schema at save time', async () => {
  const { m } = await publishFixture()

  const missing = await req('POST', '/api/items', { template_id: m.template_id, data: {} })
  assert.equal(missing.status, 422)
  assert.match(missing.json.label, /required/i)

  const typo = await req('POST', '/api/items', {
    template_id: m.template_id,
    data: { name: 'A', tilte: 'typo' },
  })
  assert.equal(typo.status, 422)
  assert.match(typo.json.label, /no field called/, 'a typo is named, not silently dropped')

  const nameField = m.fields.find((f) => f.key === 'name')
  if (nameField?.max_len) {
    const long = await req('POST', '/api/items', {
      template_id: m.template_id,
      data: { name: 'x'.repeat(nameField.max_len + 1) },
    })
    assert.equal(long.status, 422)
  }
})

test('max_len counts code points, not UTF-16 units', () => {
  const m = { fields: [{ key: 'name', type: 'text', label: 'Name', max_len: 2 }] }
  // Two emoji are two characters to a human and four UTF-16 units to JavaScript.
  // The limit is about what fits in a box, so the human count is the right one.
  assert.deepEqual(manifestMod.validateItemData(m, { name: '👋🎉' }), [])
  assert.equal(manifestMod.validateItemData(m, { name: '👋🎉🙂' }).length, 1)
})

test('an image field must point at an asset the server actually holds', async () => {
  const m = { fields: [{ key: 'photo', type: 'image', label: 'Photo' }] }
  const absent = 'blake3:' + 'b'.repeat(64)
  assert.match(
    manifestMod.validateItemData(m, { photo: absent }, { hasAsset: () => false })[0],
    /does not have/,
  )
  assert.deepEqual(manifestMod.validateItemData(m, { photo: absent }, { hasAsset: () => true }), [])
})

