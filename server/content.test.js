async function publishFixture() {
  const m = manifest()
  const created = await req('POST', '/api/templates', { id: m.template_id, name: m.name })
  assert.ok([201, 409].includes(created.status), `create said ${created.status}`)
  const pub = await req('POST', `/api/templates/${m.template_id}/publish`, {
    scene: sceneBytes().toString('base64'),
    manifest: m,
  })
  return { m, pub }
}

beforeEach(() => {
  const d = db.handle()
  d.exec('DELETE FROM items; DELETE FROM templates; DELETE FROM template_revisions;')
})

test('publishing stores the scene opaquely and the manifest as the record', async () => {
  const { m, pub } = await publishFixture()
  assert.equal(pub.status, 201)
  assert.equal(pub.json.template_rev, m.template_rev)

  // The SceneDoc is now fetchable by its address, with the exact bytes the
  // compiler emitted. The server did not parse it to get here.
  const blob = await req('GET', `/cas/${m.template_rev}`)
  assert.equal(blob.status, 200)
  assert.deepEqual(blob.bytes, sceneBytes(), 'byte-for-byte what the compiler emitted')

  const one = await req('GET', `/api/templates/${m.template_id}`)
  assert.equal(one.json.head_rev, m.template_rev)
  assert.equal(one.json.head.manifest.name, m.name)
})

test('republishing identical bytes is idempotent', async () => {
  await publishFixture()
  const { pub } = await publishFixture()
  assert.equal(pub.status, 200)
  assert.equal(pub.json.deduped, true)

  const revs = await req('GET', `/api/templates/${manifest().template_id}/revisions`)
  assert.equal(revs.json.revisions.length, 1, 'the same bytes are the same revision')
})

test('a publish whose manifest and bytes disagree is refused', async () => {
  const m = manifest()
  await req('POST', '/api/templates', { id: m.template_id, name: m.name })
  const bad = await req('POST', `/api/templates/${m.template_id}/publish`, {
    scene: Buffer.from('not the scene these belong to').toString('base64'),
    manifest: m,
  })
  assert.equal(bad.status, 422)
  assert.match(bad.json.detail, /does not match/)
})

