test('a blob round-trips and dedupes', async () => {
  const buf = Buffer.from('some bytes')
  const a = await cas.put(buf)
  const b = await cas.put(buf)
  assert.equal(a.deduped, false)
  assert.equal(b.deduped, true, 'storing identical bytes twice is one blob')
  assert.deepEqual(await cas.get(a.hash), buf)
})

test('a claimed hash that does not match the bytes is refused', async () => {
  await assert.rejects(
    () => cas.put(Buffer.from('actual'), 'blake3:' + '0'.repeat(64)),
    (e) => e.code === 'hash_mismatch',
  )
})

test('GET /cas serves ranges, which is what makes a 4 GB resume possible', async () => {
  const { hash } = await cas.put(Buffer.from('0123456789'))

  const whole = await req('GET', `/cas/${hash}`)
  assert.equal(whole.status, 200)
  assert.equal(whole.text, '0123456789')
  assert.equal(whole.headers.get('accept-ranges'), 'bytes')
  assert.equal(whole.headers.get('etag'), `"${hash}"`)

  const part = await req('GET', `/cas/${hash}`, null, { Range: 'bytes=3-5' })
  assert.equal(part.status, 206)
  assert.equal(part.text, '345')
  assert.equal(part.headers.get('content-range'), 'bytes 3-5/10')

  // Open-ended: "give me the rest", which is literally the resume request.
  const rest = await req('GET', `/cas/${hash}`, null, { Range: 'bytes=7-' })
  assert.equal(rest.status, 206)
  assert.equal(rest.text, '789')

  const past = await req('GET', `/cas/${hash}`, null, { Range: 'bytes=99-' })
  assert.equal(past.status, 416)
})

test('verify() re-hashes and reports corruption', async () => {
  const { hash } = await cas.put(Buffer.from('intact'))
  assert.equal((await cas.verify()).bad.length, 0)

  fs.writeFileSync(cas.blobPath(hash), 'tampered')
  const after = await cas.verify()
  assert.equal(after.bad.length, 1)
  assert.equal(after.bad[0].expected, hash)
})

