/** Start the app on an ephemeral port for one request. */
async function req(method, url, body, headers = {}) {
  const server = app.listen(0)
  await new Promise((r) => server.once('listening', r))
  const base = `http://127.0.0.1:${server.address().port}`
  try {
    const res = await fetch(base + url, {
      method,
      headers: { ...(body ? { 'content-type': 'application/json' } : {}), ...headers },
      // Only attach a body when there is one: fetch rejects a GET with a body.
      ...(body ? { body: JSON.stringify(body) } : {}),
    })
    // Read as bytes first. A CAS blob is binary, and res.text() would decode
    // it as UTF-8 — which silently changes the byte count and would make a
    // "the bytes survived" assertion pass or fail for the wrong reason.
    const bytes = Buffer.from(await res.arrayBuffer())
    const text = bytes.toString('utf8')
    let json = null
    try { json = JSON.parse(text) } catch { /* not json — fine for CAS bytes */ }
    return { status: res.status, json, text, bytes, headers: res.headers }
  } finally {
    server.close()
  }
}

