/**
 * Content: the CAS, the manifest gate, templates, and items.
 *
 * The test that matters most here is `blake3 agrees with the Rust compiler`.
 * Content addressing is the join between two languages, and if the two
 * implementations of the hash ever disagreed, every guarantee built on
 * `template_rev` would quietly become false rather than fail.
 */

import assert from 'node:assert/strict'
import test, { after as afterAll, before, beforeEach } from 'node:test'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'

let app, cas, db, ids, manifestMod
let tmpRoot
const FIXTURE = path.join(import.meta.dirname, '..', 'testdata', 'templates')

before(async () => {
  tmpRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'pmg-test-'))
  process.env.PMG_DB = ':memory:'
  process.env.PMG_CAS = path.join(tmpRoot, 'cas')

  cas = await import('./cas.js')
  db = await import('./db.js')
  ids = await import('./ids.js')
  manifestMod = await import('./manifest.js')
  app = (await import('./index.js')).createApp()
})

afterAll(() => fs.rmSync(tmpRoot, { recursive: true, force: true }))

/** Start the app on an ephemeral port for one request. */
async function req(method, url, body, headers = {}) {
  const server = app.listen(0)
  await new Promise((r) => server.once('listening', r))
  const base = `http://127.0.0.1:${server.address().port}`
  try {
    const res = await fetch(base + url, {
      method,
      headers: { ...(body ? { 'content-type': 'application/json' } : {}), ...headers },
      // Only attach a body when there is one: fetch rejects a GET with a body.
      ...(body ? { body: JSON.stringify(body) } : {}),
    })
    // Read as bytes first. A CAS blob is binary, and res.text() would decode
    // it as UTF-8 — which silently changes the byte count and would make a
    // "the bytes survived" assertion pass or fail for the wrong reason.
    const bytes = Buffer.from(await res.arrayBuffer())
    const text = bytes.toString('utf8')
    let json = null
    try { json = JSON.parse(text) } catch { /* not json — fine for CAS bytes */ }
    return { status: res.status, json, text, bytes, headers: res.headers }
  } finally {
    server.close()
  }
}

const sceneBytes = () => fs.readFileSync(path.join(FIXTURE, 'lower-third.pmgscene'))
const manifest = () => JSON.parse(fs.readFileSync(path.join(FIXTURE, 'lower-third.manifest.json'), 'utf8'))

// ---------------------------------------------------------------------------
// The cross-language join
// ---------------------------------------------------------------------------

test('blake3 agrees with the Rust compiler, byte for byte', async () => {
  const m = manifest()
  const computed = await cas.hashBuffer(sceneBytes())

  // `template_rev` came out of `pmg_scene::validate::compile`, which hashes the
  // canonical CBOR with the Rust blake3 crate. This asserts hash-wasm agrees.
  // If this ever fails, content addressing is broken across the boundary and
  // nothing downstream of it means what it says.
  assert.equal(computed, m.template_rev)
})

test('blake3 matches the published test vector', async () => {
  // An independent anchor, so a bug that corrupted BOTH sides identically
  // (a wrong fixture regenerated by the wrong code) still gets caught.
  assert.equal(
    await cas.hashBuffer(Buffer.from('hello')),
    'blake3:ea8f163db38682925e4491c5e58d4bb3506ef8c14eb78a86e908c5624a67200f',
  )
})

